using System.Numerics;
using Shared.GameFormats.RigidModel;
using Shared.GameFormats.RigidModel.LodHeader;

namespace Editors.PackOptimizer.Core
{
    /// <summary>Per-LOD numbers behind the detector's verdict (LOD 0 is the reference; no row for it).</summary>
    public sealed record EditorLodLevelSignals(
        int LodIndex,
        double Factor,
        int Parts,
        int Vertices,
        int Triangles,
        /// <summary>Triangles the old AssetEditor decimator would aim for: sum over LOD0 parts of min(tris, ceil(factor * LOD0 part vertices)).</summary>
        int ExpectedTriangles,
        /// <summary>Same target computed from LOD0 triangles (what a sane decimator, or a CA artist, would produce).</summary>
        int TriangleBasedTarget,
        /// <summary>Triangles / ExpectedTriangles. Old AssetEditor LODs sit just under 1.</summary>
        double VertexTargetRatio,
        /// <summary>True when the vertex-based target is clearly lower than the LOD0 triangle count, so the LOD says something.</summary>
        bool Informative,
        bool VertexTargetMatches,
        /// <summary>Triangles / TriangleBasedTarget. Close to 1 (just under) when the LOD was decimated to factor * LOD0 triangles.</summary>
        double TriangleTargetRatio,
        bool TriangleTargetMatches,
        /// <summary>The vertex target and the triangle target are far enough apart for this LOD to separate the two.</summary>
        bool Discriminating,
        /// <summary>Parts compared one to one (only when part counts match). -1 when the LOD was not compared per part.</summary>
        int PartsCompared,
        int PartsMatching);

    public sealed record EditorLodSignals(
        int LodCount,
        int Lod0Parts,
        int Lod0Vertices,
        int Lod0Triangles,
        IReadOnlyList<EditorLodLevelSignals> Levels,
        int InformativeLevels,
        int MatchingInformativeLevels,
        bool HeaderPaddingMatches,
        bool DefaultDistancesAndQuality,
        bool Lod0ColourAllBlack,
        bool MergedPartsAtLod2Plus,
        bool NoCinematicAtLod2Plus,
        bool Lod0HasCinematic,
        /// <summary>Share of LOD1 vertices (position and UV bit-identical) that already exist in LOD0. Edge-collapse tools that keep original vertices score near 1; the old decimator averaged positions and scores low.</summary>
        double Lod1VertexReuse,
        /// <summary>Share of LOD0 vertices with mirrored tangent frame (cross(N,T) opposite B), and the same for the last LOD. The old decimator rebuilt B as cross(N,T) and lost all mirroring.</summary>
        double Lod0MirroredShare,
        double LastLodMirroredShare,
        /// <summary>Share of vertices in LOD 1+ whose colour is exactly (0,0,0,1), what AssetEditor writes for every vertex it saves.</summary>
        double LodsBlackColourShare,
        double Lod0BlackColourShare);

    /// <summary>How the LODs were recognised, strongest first.</summary>
    public enum EditorLodEvidence
    {
        None,
        /// <summary>Triangle counts follow the 0.75/0.5/0.25 style schedule, but nothing ties them to AssetEditor. CA ships exactly one such rigid (grn_wyvern_skullmuncher_01), which is accepted; still an acting tier.</summary>
        ScheduleOnly,
        /// <summary>Exact schedule on triangles plus an AssetEditor marker (LOD header padding 125/136/174, or black vertex colour on every vertex of every LOD).</summary>
        ScheduleWithEditorMarker,
        /// <summary>Exact triangle schedule, more than 2% of LOD0 vertices have a mirrored tangent frame and the last LOD has none: the old decimator rebuilt B as cross(N,T).</summary>
        ScheduleWithLostMirroring,
        /// <summary>LOD triangle counts equal ceil(factor * LOD0 vertex count) on every informative LOD: the old editor's vertex-count bug.</summary>
        VertexCountTarget,
    }

    public sealed record EditorLodVerdict(bool IsEditorGenerated, EditorLodEvidence Evidence, string Reason, EditorLodSignals Signals);

    /// <summary>
    /// Recognises rigid models whose LOD 1+ were generated by AssetEditor's old managed decimator.
    /// That decimator took its triangle target as <c>ceil(factor * LOD0 vertex count)</c> (a vertex count where a
    /// triangle count belonged) with factors 0.75/0.5/0.25 for four LODs. The strong signal is therefore that every
    /// LOD has about <c>factor * LOD0 part vertices</c> triangles, which CA-authored LODs do not.
    /// The header padding, default distances and vertex colour are only supporting evidence: other tools write them too.
    /// </summary>
    public static class EditorLodDetector
    {
        /// <summary>Parts/LODs with fewer LOD0 triangles than this tell nothing: rounding dominates.</summary>
        public const int MinimumLod0Triangles = 60;
        /// <summary>The vertex-based target must be at most this fraction of the LOD0 triangles for a LOD to be informative.</summary>
        public const double InformativeTargetFraction = 0.90;
        /// <summary>A LOD matches its target when it is within this fraction of it, or within <see cref="MatchSlackTriangles"/> triangles.</summary>
        public const double MatchTolerance = 0.01;
        public const int MatchSlackTriangles = 2;
        /// <summary>The two targets must differ by more than this fraction (and 4 triangles) for a LOD to tell the vertex bug from a sane triangle target.</summary>
        public const double DiscriminatingFraction = 0.03;
        /// <summary>
        /// Both tiers need at least four LODs (the editor's default), so three informative levels. With three LODs CA ships six rigids
        /// (building destruct pieces, a cliff, a crop) whose two LODs happen to land on the vertex target within 1%.
        /// </summary>
        public const int MinimumLods = 4;
        public const int MinimumInformativeLevels = 3;
        /// <summary>LOD0 must have more than this share of mirrored vertices for lost mirroring to count.</summary>
        public const double MinimumMirroredShare = 0.02;

        public static EditorLodVerdict Analyze(RmvFile rigid)
        {
            ArgumentNullException.ThrowIfNull(rigid);
            var lodCount = rigid.ModelList?.Length ?? 0;
            var lod0 = lodCount > 0 ? rigid.ModelList![0] : [];
            var lod0Triangles = lod0.Sum(Triangles);
            var lod0Vertices = lod0.Sum(Vertices);
            var levels = new List<EditorLodLevelSignals>();

            for (var lod = 1; lod < lodCount; lod++)
                levels.Add(AnalyzeLevel(rigid, lod, lodCount));

            var informative = levels.Count(x => x.Informative);
            var matching = levels.Count(x => x.Informative && x.VertexTargetMatches);
            var signals = new EditorLodSignals(
                lodCount, lod0.Length, lod0Vertices, lod0Triangles, levels, informative, matching,
                HeaderPaddingMatches: HeaderPaddingMatches(rigid),
                DefaultDistancesAndQuality: DefaultDistancesAndQuality(rigid),
                Lod0ColourAllBlack: Lod0ColourAllBlack(lod0),
                MergedPartsAtLod2Plus: lodCount > 2 && lod0.Length > 1 && Enumerable.Range(2, lodCount - 2).Any(i => rigid.ModelList[i].Length < lod0.Length),
                NoCinematicAtLod2Plus: lodCount > 2 && Enumerable.Range(2, lodCount - 2).All(i => rigid.ModelList[i].All(m => m.Material?.BinaryVertexFormat != VertexFormat.Cinematic)),
                Lod0HasCinematic: lod0.Any(m => m.Material?.BinaryVertexFormat == VertexFormat.Cinematic),
                Lod1VertexReuse: lodCount > 1 ? VertexReuse(lod0, rigid.ModelList[1]) : 0,
                Lod0MirroredShare: MirroredShare(lod0),
                LastLodMirroredShare: lodCount > 1 ? MirroredShare(rigid.ModelList[lodCount - 1]) : 0,
                LodsBlackColourShare: BlackColourShare(rigid.ModelList.Skip(1).SelectMany(x => x)),
                Lod0BlackColourShare: BlackColourShare(lod0));

            if (lodCount < MinimumLods)
                return new EditorLodVerdict(false, EditorLodEvidence.None, "fewer than four LODs", signals);
            if (lod0Triangles < MinimumLod0Triangles)
                return new EditorLodVerdict(false, EditorLodEvidence.None, "LOD0 too small to judge", signals);

            var informativeLevels = levels.Where(x => x.Informative).ToList();
            var discriminating = informativeLevels.Count(x => x.Discriminating);
            if (informativeLevels.Count >= MinimumInformativeLevels && discriminating >= MinimumInformativeLevels && informativeLevels.All(x => x.VertexTargetMatches))
                return new EditorLodVerdict(true, EditorLodEvidence.VertexCountTarget, "triangles = ceil(factor * LOD0 vertices) on every informative LOD", signals);

            if (levels.All(x => x.TriangleTargetMatches))
            {
                var marker = signals.HeaderPaddingMatches || (signals.Lod0BlackColourShare >= 0.999 && signals.LodsBlackColourShare >= 0.999);
                if (marker)
                    return new EditorLodVerdict(true, EditorLodEvidence.ScheduleWithEditorMarker, "exact factor schedule on triangles with an editor marker", signals);
                if (signals.Lod0MirroredShare > MinimumMirroredShare && signals.LastLodMirroredShare == 0)
                    return new EditorLodVerdict(true, EditorLodEvidence.ScheduleWithLostMirroring, "exact factor schedule on triangles and the tangent mirroring is gone from the last LOD", signals);
                return new EditorLodVerdict(true, EditorLodEvidence.ScheduleOnly, "exact factor schedule on triangles, no editor marker", signals);
            }

            return new EditorLodVerdict(false, EditorLodEvidence.None, "no LOD target fingerprint", signals);
        }

        /// <summary>The factor the old editor used for LOD <paramref name="lodIndex"/> of <paramref name="lodCount"/> (lerp 0.25..1).</summary>
        public static double Factor(int lodIndex, int lodCount)
        {
            var t = (1.0 / (lodCount - 1)) * (lodCount - 1 - lodIndex);
            if (double.IsNaN(t))
                t = 1;
            return 0.25 + (1.0 - 0.25) * t;
        }

        private static EditorLodLevelSignals AnalyzeLevel(RmvFile rigid, int lod, int lodCount)
        {
            var lod0 = rigid.ModelList[0];
            var parts = rigid.ModelList[lod];
            var factor = (double)(float)Factor(lod, lodCount);

            var expected = 0;
            var triangleTarget = 0;
            foreach (var part in lod0)
            {
                var t = Triangles(part);
                expected += (int)Math.Min(t, Math.Ceiling(Vertices(part) * factor));
                triangleTarget += (int)Math.Min(t, Math.Ceiling(t * factor));
            }

            var triangles = parts.Sum(Triangles);
            var lod0Triangles = lod0.Sum(Triangles);
            var ratio = expected == 0 ? 0 : triangles / (double)expected;
            var informative = lod0Triangles >= MinimumLod0Triangles && expected <= InformativeTargetFraction * lod0Triangles;
            var matches = Within(triangles, expected);
            var triRatio = triangleTarget == 0 ? 0 : triangles / (double)triangleTarget;
            var triMatches = Within(triangles, triangleTarget);
            var discriminating = informative && Math.Abs(expected - triangleTarget) > Math.Max(4, DiscriminatingFraction * triangleTarget);

            var compared = -1;
            var matchingParts = 0;
            if (parts.Length == lod0.Length)
            {
                compared = 0;
                for (var i = 0; i < parts.Length; i++)
                {
                    var t0 = Triangles(lod0[i]);
                    var target = (int)Math.Ceiling(Vertices(lod0[i]) * factor);
                    if (t0 < MinimumLod0Triangles / 2 || target > InformativeTargetFraction * t0)
                        continue;

                    compared++;
                    if (Within(Triangles(parts[i]), target))
                        matchingParts++;
                }
            }

            return new EditorLodLevelSignals(
                lod, factor, parts.Length, parts.Sum(Vertices), triangles, expected, triangleTarget,
                ratio, informative, matches, triRatio, triMatches, discriminating, compared, matchingParts);
        }

        private static double VertexReuse(RmvModel[] lod0, RmvModel[] lod)
        {
            var known = new HashSet<(uint, uint, uint, uint, uint)>();
            foreach (var part in lod0)
            {
                foreach (var v in part.Mesh.VertexList)
                    known.Add(Key(v));
            }

            var total = 0;
            var reused = 0;
            foreach (var part in lod)
            {
                foreach (var v in part.Mesh.VertexList)
                {
                    total++;
                    if (known.Contains(Key(v)))
                        reused++;
                }
            }

            return total == 0 ? 0 : reused / (double)total;
        }

        private static (uint, uint, uint, uint, uint) Key(Shared.GameFormats.RigidModel.Vertex.CommonVertex v)
            => (BitConverter.SingleToUInt32Bits(v.Position.X), BitConverter.SingleToUInt32Bits(v.Position.Y),
                BitConverter.SingleToUInt32Bits(v.Position.Z), BitConverter.SingleToUInt32Bits(v.Uv.X), BitConverter.SingleToUInt32Bits(v.Uv.Y));

        private static double BlackColourShare(IEnumerable<RmvModel> parts)
        {
            var total = 0;
            var black = 0;
            foreach (var part in parts)
            {
                foreach (var v in part.Mesh.VertexList)
                {
                    total++;
                    if (v.Colour == new Vector4(0, 0, 0, 1))
                        black++;
                }
            }

            return total == 0 ? 0 : black / (double)total;
        }

        private static double MirroredShare(RmvModel[] parts)
        {
            var total = 0;
            var mirrored = 0;
            foreach (var part in parts)
            {
                foreach (var v in part.Mesh.VertexList)
                {
                    total++;
                    if (Vector3.Dot(Vector3.Cross(v.Normal, v.Tangent), v.BiNormal) < 0)
                        mirrored++;
                }
            }

            return total == 0 ? 0 : mirrored / (double)total;
        }

        private static bool Within(int actual, int target)
            => Math.Abs(actual - target) <= Math.Max(MatchSlackTriangles, MatchTolerance * target);

        private static int Triangles(RmvModel model) => (model.Mesh?.IndexList?.Length ?? 0) / 3;
        private static int Vertices(RmvModel model) => model.Mesh?.VertexList?.Length ?? 0;

        private static bool HeaderPaddingMatches(RmvFile rigid)
        {
            if (rigid.LodHeaders is not { Length: > 0 })
                return false;

            return rigid.LodHeaders.All(x => x is Rmv2LodHeader_V7_V8 h && h._padding0 == 125 && h._padding1 == 136 && h._padding2 == 174);
        }

        private static bool DefaultDistancesAndQuality(RmvFile rigid)
        {
            if (rigid.LodHeaders is not { Length: > 0 })
                return false;

            float[] distances = [20, 80, 100, 10000, 10000, 10000];
            byte[] quality = [2, 0, 0, 0, 0, 0, 0];
            if (rigid.LodHeaders.Length > distances.Length)
                return false;

            for (var i = 0; i < rigid.LodHeaders.Length; i++)
            {
                if (rigid.LodHeaders[i].LodCameraDistance != distances[i] || rigid.LodHeaders[i].QualityLvl != quality[i])
                    return false;
            }

            return true;
        }

        private static bool Lod0ColourAllBlack(RmvModel[] lod0)
        {
            var any = false;
            foreach (var part in lod0)
            {
                foreach (var vertex in part.Mesh.VertexList)
                {
                    any = true;
                    if (vertex.Colour != new Vector4(0, 0, 0, 1))
                        return false;
                }
            }

            return any;
        }
    }
