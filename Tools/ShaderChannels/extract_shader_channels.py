"""Builds Wh3ShaderTextureChannels.json: the texture channels each unit shader samples.

Input: a git repository holding the game's compiled shader cache (fxc/*.hlsl_compiled, a FASTBIN0
header followed by DXBC) on a branch, and fxc.exe from the Windows SDK for disassembly.

For every pixel-shader blob of the weighted2_*, weighted4_* and rigid_* shaders the script maps
each bound texture (t_xml_* resource name -> tN register) to the channels its sample/ld/gather
instructions read (destination mask through the resource swizzle; gather4 reads one channel).
Channels are unioned over every pixel-shader permutation of a shader. A slot that a shader binds
but never samples gets an empty string.

Usage (from WSL or Windows Python):
    python extract_shader_channels.py <repo> <branch> <fxc.exe> <work dir> <output json>
"""
import json
import os
import re
import subprocess
import sys
import tarfile

repo, branch, fxc, work, output = sys.argv[1:6]
git = 'git.exe' if os.name != 'nt' and os.path.exists('/mnt/c') else 'git'

os.makedirs(work, exist_ok=True)
tar_path = os.path.join(work, 'fxc.tar')
with open(tar_path, 'wb') as tar_file:
    subprocess.run(
        [git, '-C', repo, 'archive', branch, '--',
         ':(glob)fxc/shaders_weighted[24]_*', ':(glob)fxc/shaders_rigid_*'],
        stdout=tar_file, check=True)
with tarfile.open(tar_path) as archive:
    archive.extractall(work)

commit = subprocess.run([git, '-C', repo, 'rev-parse', branch], capture_output=True, text=True,
                        check=True).stdout.strip()
build = subprocess.run([git, '-C', repo, 'show', f'{branch}:text/build_info'], capture_output=True,
                       text=True).stdout.split()

instruction = re.compile(r'^\s*(\w+)(?:\([^)]*\))*\s+(r\d+|o\d+)\.([xyzw]+),\s*(.*)$')
binding = re.compile(r'^// (t_\w+)\s+texture\s+\w+\s+\w+\s+(t\d+)', re.M)
table, blobs = {}, {}
fxc_dir = os.path.join(work, 'fxc')
for name in sorted(os.listdir(fxc_dir)):
    data = open(os.path.join(fxc_dir, name), 'rb').read()
    start = data.find(b'DXBC')
    if start < 0 or b'PIXEL_SHADER' not in data[:start]:
        continue
    shader = re.sub(r'_xml_hlsl_[0-9a-f]+\.hlsl_compiled$', '', name).replace('shaders_', '', 1)
    dxbc = os.path.join(work, 'blob.dxbc')
    open(dxbc, 'wb').write(data[start:])
    path = subprocess.run(['wslpath', '-w', dxbc], capture_output=True, text=True).stdout.strip() \
        if os.name != 'nt' else dxbc
    text = subprocess.run([fxc, '/nologo', '/dumpbin', path], capture_output=True, text=True).stdout
    if 'ps_5_0' not in text:
        raise SystemExit(f'disassembly failed: {name}')
    registers = {register: slot for slot, register in binding.findall(text)}
    slots = table.setdefault(shader, {})
    blobs[shader] = blobs.get(shader, 0) + 1
    for slot in registers.values():
        if slot.startswith('t_xml_'):
            slots.setdefault(slot, set())
    for line in text.splitlines():
        match = instruction.match(line)
        if not match:
            continue
        opcode, mask, rest = match.group(1), match.group(3), match.group(4)
        for register, swizzle in re.findall(r'\b(t\d+)\.([xyzw]{4})', rest):
            slot = registers.get(register)
            if slot is None or not slot.startswith('t_xml_'):
                continue
            read = {swizzle[0]} if opcode.startswith('gather4') else {swizzle['xyzw'.index(c)] for c in mask}
            slots[slot] |= read


def rgba(channels):
    return ''.join('rgba'[i] for i, c in enumerate('xyzw') if c in channels)


result = {
    'source': f'{repo} branch {branch} commit {commit}; build_info {" ".join(build[1:3])} '
              f'{" ".join(build[5:7])}; generated by Tools/ShaderChannels/extract_shader_channels.py',
    'meaning': 'shader name (shaders/<name>.xml.shader) -> t_xml_* slot -> channels any pixel-shader '
               'permutation samples, unioned; empty = bound but never sampled; a slot absent from a '
               'shader is not bound by it',
    'pixelShaderBlobs': sum(blobs.values()),
    'shaders': {shader: {slot: rgba(table[shader][slot]) for slot in sorted(table[shader])}
                for shader in sorted(table)},
}
with open(output, 'w', newline='\n') as handle:
    json.dump(result, handle, indent=1, sort_keys=False)
    handle.write('\n')
print(f'{len(table)} shaders, {result["pixelShaderBlobs"]} pixel-shader blobs -> {output}')
